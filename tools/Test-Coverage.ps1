param(
    # Floor for merged line coverage of hand-written code. This is the only
    # place it is set; CI calls the script without the parameter.
    [double]$MinimumLinePercent = 64,
    [string]$Configuration = "Release",
    [switch]$NoBuild,
    # Which tests to run before the reports are merged.
    #   All              everything. The database tests start their own
    #                    PostgreSQL 18 (see DEV_SETUP.md, "Database tests").
    #   WithoutDatabase  everything that needs no database: CI's Windows half.
    #   DatabaseOnly     the database tests alone: CI's Linux half, because a
    #                    Windows runner cannot run the PostgreSQL container.
    #   None             run nothing; merge the reports already under
    #                    artifacts\coverage (CI's last step, with both halves).
    [ValidateSet('All', 'WithoutDatabase', 'DatabaseOnly', 'None')]
    [string]$Tests = 'All',
    # Leave the reports for a later merge instead of judging this half alone.
    [switch]$SkipThreshold
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
$resultsDirectory = [IO.Path]::Combine($repoRoot, "artifacts", "coverage")
$resolvedRepoRoot = [IO.Path]::GetFullPath($repoRoot).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
$resolvedResults = [IO.Path]::GetFullPath($resultsDirectory)
if (-not $resolvedResults.StartsWith($resolvedRepoRoot, [StringComparison]::OrdinalIgnoreCase)) {
    throw "Coverage results directory resolved outside the repository: $resolvedResults"
}

# The trait every test that needs the database carries.
$databaseTests = 'Category=Postgres'
$apiTests = [IO.Path]::Combine($repoRoot, "tests", "ShowroomBilling.Tests", "ShowroomBilling.Tests.csproj")
$desktopTests = [IO.Path]::Combine($repoRoot, "tests", "ShowroomBilling.Desktop.Tests", "ShowroomBilling.Desktop.Tests.csproj")
$runs = switch ($Tests) {
    'All' { @(@{ Project = $apiTests }, @{ Project = $desktopTests }) }
    'WithoutDatabase' { @(@{ Project = $apiTests; Filter = 'Category!=Postgres' }, @{ Project = $desktopTests }) }
    'DatabaseOnly' { @(@{ Project = $apiTests; Filter = $databaseTests }) }
    'None' { @() }
}

if ($Tests -ne 'None') {
    if (Test-Path -LiteralPath $resolvedResults) {
        Remove-Item -LiteralPath $resolvedResults -Recurse -Force
    }
    New-Item -ItemType Directory -Path $resolvedResults | Out-Null
}

foreach ($run in $runs) {
    $projectResults = Join-Path $resolvedResults ([IO.Path]::GetFileNameWithoutExtension($run.Project))
    $testArguments = @(
        "test",
        "--project", $run.Project,
        "--configuration", $Configuration,
        "--results-directory", $projectResults
    )
    if ($NoBuild) {
        $testArguments += "--no-build"
    }
    if ($run.Filter) {
        $testArguments += @("--filter", $run.Filter)
    }
    # The bracketed patterns are written here as quoted literals, not carried
    # in the array: on Linux PowerShell expands an unquoted `[...]*` argument
    # to the files it matches before the command sees it.
    #
    # The exclusion is code generated by EF tooling: about 21,000 lines that
    # no test in this run executes. Left in, they dominate the figure and
    # every new migration lowers it.
    & dotnet @testArguments -- `
        --coverlet `
        --coverlet-output-format cobertura `
        --coverlet-include '[ShowroomBilling.*]*' `
        --coverlet-include '[TallyWrapper*]*' `
        --coverlet-exclude '[ShowroomBilling.Infrastructure]ShowroomBilling.Infrastructure.Persistence.Migrations.*' `
        --report-trx
    if ($LASTEXITCODE -ne 0) {
        exit $LASTEXITCODE
    }
}

if ($SkipThreshold) {
    return
}

$reports = @()
if (Test-Path -LiteralPath $resolvedResults) {
    $reports = @(Get-ChildItem -LiteralPath $resolvedResults -Recurse -Filter "coverage.cobertura*.xml")
}
if ($reports.Count -eq 0) {
    throw "No Cobertura coverage reports were found under $resolvedResults."
}

# Each test run writes its own report and they load the same assemblies
# (Contracts, Application, Printing; Infrastructure in both halves of a split
# run). Adding the reports' totals would count those lines twice, and a line
# covered by only one run as half covered. Merge per source line instead: a
# line is covered if any report hit it.
$lineHits = @{}
foreach ($report in $reports) {
    [xml]$document = Get-Content -LiteralPath $report.FullName
    foreach ($class in $document.SelectNodes('//class')) {
        # From the project folder on, with one kind of slash: the same file
        # then has the same name in a report written on Windows and on Linux,
        # whatever folder each machine checked the repository out to.
        $file = $class.GetAttribute('filename').Replace('\', '/')
        if ($file -cmatch '(?:^|/)(ShowroomBilling[^/]*/.*)$') {
            $file = $Matches[1]
        }
        foreach ($line in $class.SelectNodes('lines/line')) {
            $key = "$file|$($line.GetAttribute('number'))"
            $hits = [long]$line.GetAttribute('hits')
            if (-not $lineHits.ContainsKey($key) -or $hits -gt $lineHits[$key]) {
                $lineHits[$key] = $hits
            }
        }
    }
}

$valid = $lineHits.Count
if ($valid -le 0) {
    throw "Coverage reports did not contain any valid source lines."
}
$covered = @($lineHits.Values | Where-Object { $_ -gt 0 }).Count

$percent = 100.0 * $covered / $valid
Write-Host ("Merged line coverage: {0:N2}% ({1}/{2}) from {3} report(s)" -f $percent, $covered, $valid, $reports.Count)
if ($percent + 0.0001 -lt $MinimumLinePercent) {
    throw ("Line coverage {0:N2}% is below the required {1:N2}%." -f $percent, $MinimumLinePercent)
}
